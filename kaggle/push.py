"""Bundle the `ser` package with a job script and run it as a Kaggle kernel.

    python kaggle/push.py extract              # GPU (T4): per-layer embeddings for every encoder
    python kaggle/push.py evaluate             # CPU: probes, 5-fold actor CV, website models
    python kaggle/push.py extract --dry-run    # only write kaggle/build/<job>/, don't push

The kernel is a single script: the local source files are embedded in it, so a run always uses
the working-tree code and nothing has to be pushed to GitHub first. Fetch results with

    kaggle kernels status mohameddddt/ser-extract-embeddings
    kaggle kernels output mohameddddt/ser-evaluate -p artifacts/kaggle
"""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HERE = ROOT / "kaggle"
USER = "mohameddddt"
SOURCES = sorted((ROOT / "ser").glob("*.py")) + [ROOT / "train_embeddings.py"]

JOBS = {
    "extract": {
        "title": "SER extract embeddings",
        "enable_gpu": True,
        "machine_shape": "NvidiaTeslaT4",
        "kernel_sources": [],
    },
    "evaluate": {
        "title": "SER evaluate",
        "enable_gpu": False,
        "kernel_sources": [f"{USER}/ser-extract-embeddings"],
    },
}

BOOTSTRAP = '''\
# Generated by kaggle/push.py: the repo's source files, written out before the job runs.
import os, sys
_SRC = "/tmp/ser_src"
for _rel, _text in FILES.items():
    _path = os.path.join(_SRC, _rel)
    os.makedirs(os.path.dirname(_path), exist_ok=True)
    with open(_path, "w", encoding="utf-8") as _f:
        _f.write(_text)
sys.path.insert(0, _SRC)
'''


def build(job):
    spec = JOBS[job]
    slug = spec["title"].lower().replace(" ", "-")
    out = HERE / "build" / job
    out.mkdir(parents=True, exist_ok=True)

    files = {str(p.relative_to(ROOT)).replace("\\", "/"): p.read_text(encoding="utf-8-sig") for p in SOURCES}
    script = f"FILES = {json.dumps(files, indent=1)}\n\n{BOOTSTRAP}\n" + (HERE / f"{job}.py").read_text(encoding="utf-8")
    (out / "run.py").write_text(script, encoding="utf-8")

    meta = {
        "id": f"{USER}/{slug}",
        "title": spec["title"],
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": spec["enable_gpu"],
        "enable_internet": True,
        "dataset_sources": ["ejlok1/cremad"],
        "kernel_sources": spec["kernel_sources"],
        "competition_sources": [],
    }
    if "machine_shape" in spec:
        meta["machine_shape"] = spec["machine_shape"]
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return out, meta["id"]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("job", choices=list(JOBS))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    out, kernel_id = build(args.job)
    print(f"built {out.relative_to(ROOT)} ({kernel_id})")
    if not args.dry_run:
        subprocess.run(["kaggle", "kernels", "push", "-p", str(out)], check=True)


if __name__ == "__main__":
    main()
